// Middleware
app.use(cors({
  origin: 'http://localhost:4200'
}));

app.use(express.json());

// PostgreSQL connection
const pool = new Pool({
  connectionString: process.env.DATABASE_URL
});

const paymentDir = path.join(
  process.cwd(),
  'uploads',
  'payments'
);

fs.mkdirSync(paymentDir, { recursive: true });

// Multer storage configuration
const storage = multer.diskStorage({
  destination: (req, file, cb) => {
    cb(null, paymentDir);
  },

  filename: (req, file, cb) => {
    const uniqueName =
      Date.now() + '-' + file.originalname.replace(/[^a-zA-Z0-9.-]/g, '_');

    cb(null, uniqueName);
  }
});

// Allow image files only
const upload = multer({
  storage: storage,
  limits: {
    fileSize: 5 * 1024 * 1024 // 5 MB
  },
  fileFilter: (req, file, cb) => {
    const allowedTypes = ['image/jpeg', 'image/png', 'image/jpg'];

    if (allowedTypes.includes(file.mimetype)) {
      cb(null, true);
    } else {
      cb(new Error('Only JPG and PNG images are allowed.'));
    }
  }
});

// Check the database connection and create the table
async function initializeDatabase() {
  // Verify the PostgreSQL connection
  await pool.query('SELECT NOW()');
await pool.query('DROP TABLE IF EXISTS appointments CASCADE');
  // Create appointments table if it does not exist
  await pool.query(`
    CREATE TABLE IF NOT EXISTS appointments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL,
      concern TEXT NOT NULL,
      preferred_date TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
       payment_screenshot TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  console.log('PostgreSQL connected successfully.');
  console.log('Appointments table is ready.');
}

// Admin authentication
const ADMIN_KEY = process.env.ADMIN_KEY || 'change-me';

function requireAdmin(req, res, next) {
  if (req.header('x-admin-key') !== ADMIN_KEY) {
    return res.status(401).json({
      error: 'Unauthorized. Valid admin key required.'
    });
  }

  next();
}

