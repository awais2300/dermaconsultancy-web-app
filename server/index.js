
require('dotenv').config();

const express = require('express');
const cors = require('cors');
const path = require('path');
const { Pool } = require('pg');

const app = express();

// Middleware
app.use(cors({
  origin: 'http://localhost:4200'
}));

app.use(express.json());

// PostgreSQL connection
const pool = new Pool({
  connectionString: process.env.DATABASE_URL
});

// Check the database connection and create the table
async function initializeDatabase() {
  // Verify the PostgreSQL connection
  await pool.query('SELECT NOW()');

  // Create appointments table if it does not exist
  await pool.query(`
    CREATE TABLE IF NOT EXISTS appointments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL,
      concern TEXT NOT NULL,
      preferred_date TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);

  console.log('PostgreSQL connected successfully.');
  console.log('Appointments table is ready.');
}

// Admin authentication
const ADMIN_KEY = process.env.ADMIN_KEY || 'change-me';

function requireAdmin(req, res, next) {
  if (req.header('x-admin-key') !== ADMIN_KEY) {
    return res.status(401).json({
      error: 'Unauthorized. Valid admin key required.'
    });
  }

  next();
}

// --------------------------------------------------
// API 1: Submit a new appointment (public)
// POST /api/appointments
// --------------------------------------------------
app.post('/api/appointments', async (req, res, next) => {
  try {
    const {
      name,
      email,
      phone,
      concern,
      preferredDate
    } = req.body;

    // Validate required fields
    if (
      !name ||
      !email ||
      !phone ||
      !concern ||
      !preferredDate
    ) {
      return res.status(400).json({
        error: 'All fields are required.'
      });
    }

    // Save appointment to PostgreSQL
    const result = await pool.query(
      `INSERT INTO appointments
        (name, email, phone, concern, preferred_date)
       VALUES ($1, $2, $3, $4, $5)
       RETURNING id, status, created_at`,
      [
        name,
        email,
        phone,
        concern,
        preferredDate
      ]
    );

    return res.status(201).json({
      message: 'Appointment request submitted successfully.',
      appointment: result.rows[0]
    });
  } catch (error) {
    next(error);
  }
});

// --------------------------------------------------
// API 2: Get all appointments (admin only)
// GET /api/appointments
// Requires x-admin-key header
// --------------------------------------------------
app.get('/api/appointments', requireAdmin, async (req, res, next) => {
  try {
    const result = await pool.query(
      `SELECT
         id,
         name,
         email,
         phone,
         concern,
         preferred_date,
         status,
         created_at
       FROM appointments
       ORDER BY created_at DESC`
    );

    return res.json(result.rows);
  } catch (error) {
    next(error);
  }
});

// --------------------------------------------------
// API 3: Update appointment status (admin only)
// PATCH /api/appointments/:id
// Status: pending, confirmed, cancelled
// Requires x-admin-key header
// --------------------------------------------------
app.patch('/api/appointments/:id', requireAdmin, async (req, res, next) => {
  try {
    const { status } = req.body;
    const appointmentId = Number(req.params.id);

    if (!Number.isInteger(appointmentId) || appointmentId < 1) {
      return res.status(400).json({
        error: 'Invalid appointment ID.'
      });
    }

    if (!['pending', 'confirmed', 'cancelled'].includes(status)) {
      return res.status(400).json({
        error: 'Status must be pending, confirmed, or cancelled.'
      });
    }

    const result = await pool.query(
      `UPDATE appointments
       SET status = $1
       WHERE id = $2
       RETURNING id, status`,
      [status, appointmentId]
    );

    if (result.rowCount === 0) {
      return res.status(404).json({
        error: 'Appointment not found.'
      });
    }

    return res.json({
      message: 'Appointment status updated successfully.',
      appointment: result.rows[0]
    });
  } catch (error) {
    next(error);
  }
});

// --------------------------------------------------
// Serve the Angular frontend
// --------------------------------------------------
const dist = path.join(
  __dirname,
  '..',
  'client',
  'dist',
  'client',
  'browser'
);

app.use(express.static(dist));

// Angular routing fallback
app.use((req, res, next) => {
  if (req.method !== 'GET' || req.path.startsWith('/api')) {
    return next();
  }

  res.sendFile(path.join(dist, 'index.html'), (error) => {
    if (error) {
      next(error);
    }
  });
});

// --------------------------------------------------
// Error handler
// --------------------------------------------------
app.use((error, req, res, next) => {
  console.error('Server error:', error);

  if (res.headersSent) {
    return next(error);
  }

  res.status(500).json({
    error: 'An internal server error occurred.'
  });
});

// --------------------------------------------------
// Start the server after PostgreSQL is ready
// --------------------------------------------------
const PORT = process.env.PORT || 3000;

initializeDatabase()
  .then(() => {
    app.listen(PORT, () => {
      console.log(`Backend running at http://localhost:${PORT}`);
    });
  })
  .catch((error) => {
    console.error(
      'Failed to connect to PostgreSQL or initialize the database:',
      error.message
    );

    process.exit(1);
  });
